-- 012_add_ai_metadata_to_facts.sql
-- Adds metadata columns for tracking AI-generated content and uniqueness validation

BEGIN;

-- Add columns to facts table for AI content tracking
ALTER TABLE IF EXISTS facts
  ADD COLUMN IF NOT EXISTS ai_generated boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS content_hash text,
  ADD COLUMN IF NOT EXISTS is_unique boolean DEFAULT true,
  ADD COLUMN IF NOT EXISTS checked_at timestamptz;

-- Add columns to quizzes table for AI content tracking
ALTER TABLE IF EXISTS quizzes
  ADD COLUMN IF NOT EXISTS ai_generated boolean DEFAULT false;

COMMIT;

-- Notes:
-- These columns track whether content was generated by AI and help prevent duplicates.
-- ai_generated: true for AI-generated content, false for manually created content
-- content_hash: Hash of normalized fact text for uniqueness checking
-- is_unique: Whether content passed uniqueness validation
-- checked_at: Timestamp when uniqueness was last checked
